def determine_license(cache_directory: Path) -> LicenseInfo:
    """Determine licensing from the dataset identity and its source repository; never infer it."""
    api_path = fetch(DATASET_API_URL, cache_directory / "dataset-api.json")
    metadata = json.loads(api_path.read_text(encoding="utf-8"))
    if metadata.get("id") != DATASET or metadata.get("sha") != DATASET_REVISION:
        raise RuntimeError("hard-v1 dataset identity or pinned revision changed")
    siblings = {entry.get("rfilename") for entry in metadata.get("siblings", [])}
    if "hard-v1/train.jsonl" not in siblings:
        raise RuntimeError("hard-v1 train partition is absent from the dataset repository")
    manifest_path = fetch(MANIFEST_URL, cache_directory / "manifest.json")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    if manifest.get("version") != "hard-v1" or manifest.get("partitions") != ["train", "development", "test"]:
        raise RuntimeError("unexpected hard-v1 source manifest")
    license_path = fetch(LICENSE_URL, cache_directory / "LICENSE")
    text = license_path.read_text(encoding="utf-8")
    required = ("Apache License", "Version 2.0", "Copyright 2026 Jared Palmer")
    if not all(marker in text for marker in required):
        raise RuntimeError("the hard-v1 source repository license cannot be determined")
    return LicenseInfo(
        "Apache-2.0",
        LICENSE_URL,
        ATTRIBUTION,
        CITATION,
        {
            "dataset_api_url": DATASET_API_URL,
            "dataset_revision": DATASET_REVISION,
            "dataset_card_license": metadata.get("cardData", {}).get("license") if isinstance(metadata.get("cardData"), dict) else None,
            "source_manifest_url": MANIFEST_URL,
            "source_repository": UPSTREAM_REPOSITORY,
            "source_revision": UPSTREAM_REVISION,
            "source_license_sha256": sha256_file(license_path),
        },
    )


def acquire_hardv1(cache_directory: Path) -> list[SourceFile]:
    """Acquire the three real hard-v1 partitions and verify the frozen manifest hashes."""
    manifest_path = fetch(MANIFEST_URL, cache_directory / "manifest.json")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    files = manifest.get("files", {})
    specifications = []
    temporary_train = Path("/tmp/hardv1_train.jsonl")
    if temporary_train.is_file():
        train_path = temporary_train
    else:
        train_path = fetch(TRAIN_URL, cache_directory / "train.jsonl")
    specifications.append(SourceFile(
        train_path, "train", "hard-v1/train.jsonl", TRAIN_URL, DATASET_REPOSITORY,
        DATASET_REVISION, DATASET_API_URL,
    ))
    for split in ("development", "test"):
        upstream_path = f"evals/hard-v1/{split}.jsonl"
        url = f"{RAW_GITHUB}/{upstream_path}"
        specifications.append(SourceFile(
            fetch(url, cache_directory / f"{split}.jsonl"), split, upstream_path, url,
            UPSTREAM_REPOSITORY, UPSTREAM_REVISION, UPSTREAM_API_URL,
        ))
    for source in specifications:
        filename = "train.jsonl" if source.upstream_split == "train" else f"{source.upstream_split}.jsonl"
        expected = files.get(filename, {}).get("sha256")
        actual = sha256_file(source.path)
        if not isinstance(expected, str) or actual != expected:
            raise RuntimeError(f"hard-v1 integrity failure for {filename}: expected {expected}, got {actual}")
    return specifications


def split_development_rows(rows: list[dict]) -> list[dict]:
    """Assign complete development groups to deterministic, balanced canonical splits."""
    groups: dict[str, list[dict]] = collections.defaultdict(list)
    for row in rows:
        if row["split"] != "dev":
            raise ValueError("hard-v1 development input must use the canonical dev split")
        groups[row["group_id"]].append(row)
    totals = {"dev": 0, "calibration": 0}
    assignments = {}
    for group_id in sorted(
        groups, key=lambda value: stable_id("hard-v1-development-split", value)
    ):
        split = min(totals, key=lambda value: (totals[value], value))
        assignments[group_id] = split
        totals[split] += len(groups[group_id])
    admitted = []
    for row in rows:
        admitted_row = {**row, "split": assignments[row["group_id"]]}
        validate_record(admitted_row)
        admitted.append(admitted_row)
    if max(totals.values()) - min(totals.values()) > 1:
        raise ValueError(f"hard-v1 development split is not balanced: {totals}")
    return admitted


def prepare(root: Path) -> dict:
    """Build the canonical hard-v1 part from the independently verified conversion."""
    root = root.resolve()
    audit = root / ".audit"
    converted = audit / "hardv1-converted"
    conversion_receipt_path = audit / "hardv1-conversion.json"
    conversion_receipt = json.loads(conversion_receipt_path.read_text(encoding="utf-8"))
    inputs = {}
    for split, upstream in (("train", "train"), ("dev", "development")):
        path = converted / f"{split}.jsonl"
        expected = conversion_receipt["per_split"][upstream]["output_sha256"]
        actual = sha256_file(path)
        if actual != expected:
            raise ValueError(
                f"hard-v1 converted {split} hash mismatch: expected {expected}, got {actual}"
            )
        inputs[split] = [row for _, row in _read_source(path)]

    train = inputs["train"]
    if len(train) != 7_876 or any(row["split"] != "train" for row in train):
        raise ValueError("hard-v1 train conversion must contain exactly 7,876 train rows")
    for row in train:
        validate_record(row)
    development = split_development_rows(inputs["dev"])
    counts = collections.Counter(row["split"] for row in (*train, *development))
    expected_counts = {"train": 7_876, "dev": 464, "calibration": 464}
    if dict(counts) != expected_counts:
        raise ValueError(
            f"hard-v1 admission counts differ from the fixed contract: {dict(counts)}"
        )
    groups = {
        split: len({row["group_id"] for row in (*train, *development) if row["split"] == split})
        for split in expected_counts
    }
    rows = [*train, *development]
    part_path = root / "data" / "parts" / "hardv1.jsonl"
    write_jsonl(part_path, rows)
    license_source = audit / "hardv1-source" / "LICENSE"
    license_path = root / "data" / "raw" / "hard-v1" / "LICENSE"
    license_path.parent.mkdir(parents=True, exist_ok=True)
    license_path.write_bytes(license_source.read_bytes())
    source_path = root / "data" / "sources" / "hard-v1.json"
    write_json(source_path, {
        "source": SOURCE,
        "revision": {
            "dataset": DATASET_REVISION,
            "upstream": UPSTREAM_REVISION,
        },
        "repository": {
            "dataset": DATASET_REPOSITORY,
            "upstream": UPSTREAM_REPOSITORY,
        },
        "upstream_split": {
            "train": "train",
            "dev_and_calibration": "development",
            "external_only": "test",
        },
        "license": conversion_receipt["license"]["name"],
        "license_url": conversion_receipt["license"]["url"],
        "license_path": license_path.relative_to(root / "data").as_posix(),
        "processing": (
            "All converted train rows are admitted to train. Converted development groups "
            "are deterministically balanced between dev and calibration. Upstream test is external."
        ),
        "known_limits": [
            "Generated rules and labels are not human-authored judgments.",
            "The upstream hard-v1 test split is excluded from the canonical corpus.",
        ],
    })
    admission = {
        "status": "VERIFIED",
        "source": SOURCE,
        "conversion_receipt_sha256": sha256_file(conversion_receipt_path),
        "converted_hashes": {
            split: sha256_file(converted / f"{split}.jsonl") for split in ("train", "dev")
        },
        "part_path": part_path.relative_to(root).as_posix(),
        "part_sha256": sha256_file(part_path),
        "source_manifest_sha256": sha256_file(source_path),
        "license_sha256": sha256_file(license_path),
        "splits": dict(counts),
        "groups": groups,
        "record_schema_sha256": sha256_file(RECORDS_PATH),
        "upstream_test_admitted": False,
    }
    write_json(audit / "hardv1-admission.json", admission)
    return admission


def convert_hardv1(
    root: Path,
    *,
    output_directory: Path | None = None,
    receipt_path: Path | None = None,
) -> dict:
    """Public entry point: acquire, convert, native-compile, and receipt hard-v1."""
    root = root.resolve()
    audit = root / ".audit"
    cache = audit / "hardv1-source"
    license_info = determine_license(cache)
    sources = acquire_hardv1(cache)
    compiler = NativeCompiler.from_pretrained(root, media_root=root / "data")
    return convert_files(
        sources,
        (output_directory or audit / "hardv1-converted").resolve(),
        (receipt_path or audit / "hardv1-conversion.json").resolve(),
        license_info,
        compiler,
    )


