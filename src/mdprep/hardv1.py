class QuestionDrop(ValueError):
    def __init__(self, code: str, detail: str):
        super().__init__(detail)
        self.code = code
        self.detail = detail


def slug(value: str) -> str:
    """Return hard-v1's ASCII entity key for an exact display name."""
    return re.sub(r"[^a-z0-9]+", "_", value.lower()).strip("_")


def _scalar(value: object) -> str:
    if value is True:
        return "yes"
    if value is False:
        return "no"
    if value is None:
        return "not specified"
    if isinstance(value, (str, int, float)):
        return str(value)
    if isinstance(value, list):
        return ", ".join(_scalar(item) for item in value)
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))

def _render_generic(value: object, indent: int = 0) -> str:
    pad = "  " * indent
    if value is None:
        return ""
    if isinstance(value, (str, int, float, bool)):
        return str(value)
    if isinstance(value, list):
        return "\n".join(
            f"{pad}- {_render_generic(item, indent + 1).lstrip()}" for item in value
        )
    if not isinstance(value, dict):
        raise ValueError(f"unsupported structured state value: {type(value).__name__}")
    lines = []
    for key, item in value.items():
        if not isinstance(key, str) or not key:
            raise ValueError("structured state field names must be non-empty text")
        if isinstance(item, (dict, list)):
            lines.append(f"{pad}{key}:\n{_render_generic(item, indent + 1)}")
        else:
            lines.append(f"{pad}{key}: {_render_generic(item)}")
    return "\n".join(lines)




def render_state(state: object) -> str:
    """Render a hard-v1 state to deterministic plain text without losing entity names."""
    if isinstance(state, str):
        return state
    if not isinstance(state, dict):
        raise ValueError("state must be a string or object")
    required = {"decision", "hard_requirements", "selection_rule", "options"}
    if set(state) != required:
        return _render_generic(state)
    decision = state["decision"]
    requirements = state["hard_requirements"]
    rule = state["selection_rule"]
    options = state["options"]
    if not isinstance(decision, str) or not decision.strip():
        raise ValueError("structured state decision must be non-empty text")
    if not isinstance(requirements, list) or not all(isinstance(item, str) and item.strip() for item in requirements):
        raise ValueError("structured state hard_requirements must be a text list")
    if not isinstance(rule, str) or not rule.strip():
        raise ValueError("structured state selection_rule must be non-empty text")
    if not isinstance(options, dict) or not options:
        raise ValueError("structured state options must be a non-empty object")
    columns: list[str] = []
    for name, attributes in options.items():
        if not isinstance(name, str) or not name.strip() or not isinstance(attributes, dict):
            raise ValueError("structured state options require named attribute objects")
        for column in attributes:
            if not isinstance(column, str) or not column.strip():
                raise ValueError("structured state option columns must be non-empty text")
            if column not in columns:
                columns.append(column)
    lines = [decision, "", "Hard requirements:"]
    lines.extend(f"- {requirement}" for requirement in requirements)
    lines.extend(("", rule, "", "| " + " | ".join(("option", *columns)) + " |"))
    lines.append("|" + "|".join("---" for _ in range(len(columns) + 1)) + "|")
    for name, attributes in options.items():
        values = [name] + [_scalar(attributes.get(column)) for column in columns]
        lines.append("| " + " | ".join(values) + " |")
    return "\n".join(lines)


def _name_mapping(source: dict) -> tuple[dict[str, str], dict[str, str]]:
    state_names: dict[str, str] = {}
    fact_names: dict[str, str] = {}
    state = source.get("state")
    if isinstance(state, dict) and isinstance(state.get("options"), dict):
        state_names = {slug(name): name for name in state["options"] if isinstance(name, str) and slug(name)}
    facts = source.get("_meta", {}).get("facts", {})
    if isinstance(facts, dict) and isinstance(facts.get("options"), dict):
        fact_names = {slug(name): name for name in facts["options"] if isinstance(name, str) and slug(name)}
    return state_names, fact_names


def _scan_name(key: str, rendered_state: str) -> str | None:
    tokens = list(_WORD.finditer(rendered_state))
    for width in (3, 2, 1):
        matches = []
        for index in range(len(tokens) - width + 1):
            candidate = rendered_state[tokens[index].start():tokens[index + width - 1].end()]
            if slug(candidate) == key:
                matches.append(candidate)
        if matches:
            return matches[0]
    return None


def resolve_option_text(key: str, rendered_state: str, mappings: tuple[dict[str, str], dict[str, str]]) -> tuple[str | None, str]:
    """Resolve a null choice description by the required four-tier policy."""
    normalized = slug(key)
    if not normalized:
        return None, "unresolved"
    for mapping in mappings:
        if normalized in mapping:
            return mapping[normalized], "exact_mapping"
    scanned = _scan_name(normalized, rendered_state)
    if scanned:
        return scanned, "rendered_state_scan"
    fallback = normalized.replace("_", " ").title()
    if fallback.strip():
        return fallback, "title_case_fallback"
    return None, "unresolved"


